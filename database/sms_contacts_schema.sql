-- SMS Contacts table
CREATE TABLE IF NOT EXISTS sms_contacts (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    phone VARCHAR(30),
    contact_type VARCHAR(20) DEFAULT 'client' CHECK (contact_type IN ('client', 'candidate', 'other')),
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    created_by VARCHAR(255)
);

CREATE INDEX IF NOT EXISTS idx_sms_contacts_phone ON sms_contacts(phone);
CREATE INDEX IF NOT EXISTS idx_sms_contacts_type ON sms_contacts(contact_type);

ALTER TABLE sms_contacts ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow authenticated users to view sms_contacts" ON sms_contacts
    FOR SELECT USING (auth.role() = 'authenticated');

CREATE POLICY "Allow authenticated users to insert sms_contacts" ON sms_contacts
    FOR INSERT WITH CHECK (auth.role() = 'authenticated');

CREATE POLICY "Allow authenticated users to update sms_contacts" ON sms_contacts
    FOR UPDATE USING (auth.role() = 'authenticated');

CREATE POLICY "Allow authenticated users to delete sms_contacts" ON sms_contacts
    FOR DELETE USING (auth.role() = 'authenticated');

